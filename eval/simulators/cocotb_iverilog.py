"""cocotb + iverilog Simulator for CVDP cid002 / cid003.

CVDP cases ship a Python cocotb test under harness.files["src/test_<name>.py"]
plus a small runner. We stage those into a temp dir alongside the LLM-
produced DUT, write a cocotb Makefile (SIM=icarus), run `make`, and parse
the cocotb result file `results.xml` for pass/fail.

cocotb must be installed locally:  pip install cocotb
iverilog must be on PATH.
"""

import os
import re
import shutil
import subprocess
import time
import xml.etree.ElementTree as ET
from pathlib import Path

from .base import SimResult


_MAKEFILE_TEMPLATE = """\
# Auto-generated by rtlbench-mt eval/cocotb_iverilog.py
SIM ?= icarus
TOPLEVEL_LANG ?= verilog
VERILOG_SOURCES = $(PWD)/dut.sv
TOPLEVEL = {toplevel}
MODULE = {module}

include $(shell cocotb-config --makefiles)/Makefile.sim
"""


class CocotbIverilogSimulator:
    name = "cocotb_iverilog"

    def __init__(self, run_timeout: int = 180):
        if not shutil.which("iverilog"):
            raise RuntimeError("iverilog not found on PATH")
        try:
            import cocotb  # noqa: F401
        except ImportError as e:
            raise RuntimeError(
                "cocotb not installed. Run: pip install cocotb"
            ) from e
        try:
            cfg = subprocess.run(["cocotb-config", "--makefiles"],
                                 capture_output=True, text=True, check=True)
            if not cfg.stdout.strip():
                raise RuntimeError("cocotb-config returned empty path")
        except (subprocess.CalledProcessError, FileNotFoundError) as e:
            raise RuntimeError(
                "cocotb-config not on PATH; reinstall cocotb"
            ) from e
        self.run_timeout = run_timeout

    def run(self, dut_code: str, record: dict, work_dir: Path, bench: str) -> SimResult:
        if not bench.startswith("cvdp_"):
            return SimResult(
                passed=False, error=f"cocotb_iverilog only handles cvdp_*; got {bench}",
                stage="dispatch",
            )

        work_dir.mkdir(parents=True, exist_ok=True)

        # ── stage harness files into work_dir/src ────────────────────────
        harness_files = record.get("harness", {}).get("files", {})
        if not harness_files:
            return SimResult(
                passed=False, error="no harness.files in record", stage="setup",
            )

        # Find the cocotb test module (src/test_<name>.py)
        test_path_in_harness = None
        for fname in harness_files:
            if fname.endswith(".py") and "/test_" in fname:
                test_path_in_harness = fname
                break
        if test_path_in_harness is None:
            return SimResult(
                passed=False, error="no cocotb test_*.py in harness",
                stage="setup",
            )

        # Stage every harness file (preserving relative paths) under work_dir.
        # Harness keys look like 'src/test_X.py', 'docker-compose.yml', etc.
        for rel, body in harness_files.items():
            if not isinstance(body, str):
                continue
            dest = work_dir / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(body)

        # DUT goes alongside the cocotb test (so the test's relative `..`
        # navigation works).
        dut_dir = (work_dir / test_path_in_harness).parent
        (dut_dir / "dut.sv").write_text(dut_code)

        # Module name to use as TOPLEVEL = the canonical's top-level name.
        # Best signal: derive from the cocotb test module — most test_X.py
        # files set `dut = cocotb.handle.SimHandle(...)` based on a top
        # called X. Otherwise fall back to record["id"] heuristic.
        toplevel = _infer_toplevel(harness_files[test_path_in_harness], record)

        # Cocotb's MODULE expects the python module name (no .py, no path)
        py_module = Path(test_path_in_harness).stem

        # Write Makefile in dut_dir (same dir as dut.sv and test_*.py).
        (dut_dir / "Makefile").write_text(
            _MAKEFILE_TEMPLATE.format(toplevel=toplevel, module=py_module)
        )

        # ── run make ────────────────────────────────────────────────────
        env = os.environ.copy()
        env["PYTHONPATH"] = str(dut_dir) + os.pathsep + env.get("PYTHONPATH", "")
        t0 = time.time()
        try:
            rp = subprocess.run(
                ["make"],
                cwd=str(dut_dir),
                capture_output=True, text=True,
                timeout=self.run_timeout, env=env,
            )
        except subprocess.TimeoutExpired:
            return SimResult(passed=False, error="cocotb run timeout",
                             stage="run", duration_s=time.time() - t0)

        # ── parse results.xml ───────────────────────────────────────────
        results_xml = dut_dir / "results.xml"
        passed = False
        parse_err = None
        if results_xml.exists():
            try:
                root = ET.parse(results_xml).getroot()
                # cocotb writes JUnit-style XML.
                # Pass = no <failure> or <error> children under any testcase
                failures = root.findall(".//failure") + root.findall(".//error")
                passed = len(failures) == 0 and root.findall(".//testcase")
                passed = bool(passed)
            except ET.ParseError as e:
                parse_err = f"results.xml parse error: {e}"
        else:
            parse_err = "results.xml missing"

        # Always include stdout for debugging
        return SimResult(
            passed=passed,
            output=rp.stdout,
            error=(rp.stderr if rp.stderr else None) if passed else (rp.stderr or parse_err),
            stage="run",
            duration_s=time.time() - t0,
        )


_TOPLEVEL_RE = re.compile(
    r"toplevel\s*=\s*['\"]([A-Za-z_][\w]*)['\"]", re.IGNORECASE,
)


def _infer_toplevel(test_py: str, record: dict) -> str:
    """Try several signals to find the cocotb top-level module name."""
    m = _TOPLEVEL_RE.search(test_py)
    if m:
        return m.group(1)
    # cvdp ids look like cvdp_copilot_<modulename>_NNNN
    tid = record.get("id", "")
    if tid.startswith("cvdp_copilot_"):
        rest = tid[len("cvdp_copilot_"):]
        # strip trailing _NNNN
        rest = re.sub(r"_\d+$", "", rest)
        return rest
    return "dut"
